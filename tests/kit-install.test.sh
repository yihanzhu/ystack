#!/bin/bash
# Checks kit/install.sh against a scratch HOME and a copy of the kit.
set -u

root=$(git rev-parse --show-toplevel)
scratch=$(mktemp -d)
trap 'rm -rf "$scratch"' EXIT
failures=0

pass() { echo "ok - $1"; }
fail() {
  echo "not ok - $1"
  sed 's/^/#   /' "$scratch/out" 2> /dev/null
  failures=$((failures + 1))
}

export HOME=$scratch/home
kit=$HOME/git/ystack/kit
mkdir -p "$HOME/git/ystack"
cp -R "$root/kit" "$kit"
claude=$HOME/.claude/CLAUDE.md
codex=$HOME/.codex/AGENTS.md

# Runs the installer; $1 is the exit code it must return.
run() {
  local want=$1 got
  shift
  "$kit/install.sh" "$@" > "$scratch/out" 2>&1
  got=$?
  [ "$got" -eq "$want" ]
}

holds() {
  grep -q -F -- "$2" "$1"
}

if run 0 && holds "$claude" '@~/git/ystack/kit/rules/working-preferences.md' &&
  holds "$claude" '@~/git/ystack/kit/rules/claude.md' &&
  holds "$codex" '## Working preferences' && holds "$codex" '## Codex model routing'; then
  pass 'fresh install writes both blocks'
else
  fail 'fresh install writes both blocks'
fi

if run 0 --check && holds "$scratch/out" 'is current'; then
  pass 'check reports a current install'
else
  fail 'check reports a current install'
fi

cp "$claude" "$scratch/claude.before"
cp "$codex" "$scratch/codex.before"
if run 0 && [ ! -s "$scratch/out" ] && cmp -s "$claude" "$scratch/claude.before" &&
  cmp -s "$codex" "$scratch/codex.before"; then
  pass 'a second run changes nothing'
else
  fail 'a second run changes nothing'
fi

printf '%s\n' '# Owner notes' '@~/git/other/rules.md' > "$claude"
cat "$scratch/claude.before" >> "$claude"
printf '%s\n' 'Text after the block.' >> "$claude"
cp "$claude" "$scratch/claude.with-notes"
printf '\n- A new routing line.\n' >> "$kit/rules/codex.md"
if run 1 --check && holds "$scratch/out" 'stale: ~/.codex/AGENTS.md' &&
  ! holds "$scratch/out" 'CLAUDE.md'; then
  pass 'check reports a changed rule as stale'
else
  fail 'check reports a changed rule as stale'
fi
if run 0 && cmp -s "$claude" "$scratch/claude.with-notes" &&
  holds "$codex" 'A new routing line.'; then
  pass 'a refresh updates the block and keeps other text'
else
  fail 'a refresh updates the block and keeps other text'
fi

rm "$codex"
printf '%s' '<!-- Generated by another tool. -->' > "$codex"
if run 0 && [ "$(head -n 1 "$codex")" = '<!-- Generated by another tool. -->' ] &&
  [ "$(sed -n 2p "$codex")" = '' ] && holds "$codex" '<!-- ystack kit: begin'; then
  pass 'a file without markers keeps its text and gets the block'
else
  fail 'a file without markers keeps its text and gets the block'
fi

printf '%s\n' 'keep' '<!-- ystack kit: begin (old) -->' 'no end' > "$claude"
cp "$claude" "$scratch/broken"
if run 2 && holds "$scratch/out" 'broken kit markers' && cmp -s "$claude" "$scratch/broken"; then
  pass 'broken markers stop the install and change nothing'
else
  fail 'broken markers stop the install and change nothing'
fi
printf '%s\n' '<!-- ystack kit: end -->' '<!-- ystack kit: begin (old) -->' > "$claude"
if run 2 && holds "$scratch/out" 'out of order'; then
  pass 'markers out of order stop the install'
else
  fail 'markers out of order stop the install'
fi

mkdir -p "$HOME/dotfiles"
rm "$claude"
printf '%s\n' 'linked notes' > "$HOME/dotfiles/CLAUDE.md"
ln -s "$HOME/dotfiles/CLAUDE.md" "$claude"
if run 0 && [ -L "$claude" ] && holds "$HOME/dotfiles/CLAUDE.md" 'linked notes' &&
  holds "$HOME/dotfiles/CLAUDE.md" '@~/git/ystack/kit/rules/claude.md'; then
  pass 'a linked CLAUDE.md stays a link and its target is updated'
else
  fail 'a linked CLAUDE.md stays a link and its target is updated'
fi

mkdir -p "$kit/skills/ystack-demo" "$HOME/.claude/skills/someone-else"
printf '%s\n' '---' 'name: ystack-demo' '---' > "$kit/skills/ystack-demo/SKILL.md"
mkdir -p "$HOME/.agents/skills"
ln -s "$scratch/nowhere" "$HOME/.agents/skills/foreign-dangling"
if run 0 && [ "$(readlink "$HOME/.claude/skills/ystack-demo")" = "$kit/skills/ystack-demo" ] &&
  [ "$(readlink "$HOME/.agents/skills/ystack-demo")" = "$kit/skills/ystack-demo" ] &&
  [ -d "$HOME/.claude/skills/someone-else" ]; then
  pass 'kit skills are linked for both agents'
else
  fail 'kit skills are linked for both agents'
fi
if run 0 --check; then
  pass 'check accepts the links'
else
  fail 'check accepts the links'
fi
rm -r "$kit/skills/ystack-demo"
if run 0 && [ ! -L "$HOME/.claude/skills/ystack-demo" ] && [ ! -L "$HOME/.agents/skills/ystack-demo" ] &&
  [ -L "$HOME/.agents/skills/foreign-dangling" ]; then
  pass "a removed skill's links go and other links stay"
else
  fail "a removed skill's links go and other links stay"
fi
mkdir -p "$kit/skills/ystack-demo" "$HOME/.claude/skills/ystack-demo"
printf '%s\n' '---' 'name: ystack-demo' '---' > "$kit/skills/ystack-demo/SKILL.md"
if run 2 && holds "$scratch/out" 'is not this kit' && [ -d "$HOME/.claude/skills/ystack-demo" ] &&
  [ ! -L "$HOME/.claude/skills/ystack-demo" ]; then
  pass 'a folder with the same name is left alone and stops the install'
else
  fail 'a folder with the same name is left alone and stops the install'
fi
rm -r "$kit/skills/ystack-demo" "$HOME/.claude/skills/ystack-demo"

mkdir -p "$HOME/.claude/commands"
printf '%s\n' '---' 'description: Summon yshifu, the dev-team manager' '---' > "$HOME/.claude/commands/yshifu.md"
cp "$HOME/.claude/commands/yshifu.md" "$HOME/.claude/commands/yshifu.md.bak"
printf '%s\n' 'my own command' > "$HOME/.claude/commands/other.md"
if run 0 && [ ! -e "$HOME/.claude/commands/yshifu.md" ] && [ ! -e "$HOME/.claude/commands/yshifu.md.bak" ] &&
  [ -f "$HOME/.claude/commands/other.md" ]; then
  pass 'the parked yshifu command is removed and others stay'
else
  fail 'the parked yshifu command is removed and others stay'
fi
printf '%s\n' 'a yshifu file the owner wrote' > "$HOME/.claude/commands/yshifu.md"
if run 0 && [ -f "$HOME/.claude/commands/yshifu.md" ]; then
  pass 'a yshifu file without the old header stays'
else
  fail 'a yshifu file without the old header stays'
fi

elsewhere=$scratch/elsewhere/kit
mkdir -p "$scratch/elsewhere"
cp -R "$root/kit" "$elsewhere"
if "$elsewhere/install.sh" > "$scratch/out" 2>&1 && holds "$claude" "@$elsewhere/rules/claude.md"; then
  pass 'a kit outside HOME is imported by its full path'
else
  fail 'a kit outside HOME is imported by its full path'
fi

repo=$scratch/repo
git init -q "$repo"
cp -R "$root/kit" "$repo/kit"
git -C "$repo" add -A
git -C "$repo" -c user.name=t -c user.email=t@example.invalid -c core.hooksPath=/dev/null \
  commit -q -m kit
git -C "$repo" worktree add -q "$scratch/linked" 2> /dev/null
if ! "$scratch/linked/kit/install.sh" --check > "$scratch/out" 2>&1 &&
  holds "$scratch/out" 'not from a linked worktree'; then
  pass 'a linked worktree is refused'
else
  fail 'a linked worktree is refused'
fi
if "$repo/kit/install.sh" > "$scratch/out" 2>&1; then
  pass 'the main checkout of a repository is accepted'
else
  fail 'the main checkout of a repository is accepted'
fi

if [ "$failures" -gt 0 ]; then
  echo "$failures case(s) failed"
  exit 1
fi
echo "all cases passed"
