#!/bin/bash
# Checks kit/install.sh against a scratch HOME and a copy of the kit in a scratch repo.
set -u

root=$(git rev-parse --show-toplevel) || exit 1
scratch=$(mktemp -d) || exit 1
[ -n "$scratch" ] && [ -d "$scratch" ] || exit 1
trap 'rm -rf "$scratch"' EXIT
failures=0

pass() { echo "ok - $1"; }
fail() {
  echo "not ok - $1"
  sed 's/^/#   /' "$scratch/out" 2> /dev/null
  failures=$((failures + 1))
}

# Copies the kit into a new Git repository at $1.
kit_repo() {
  mkdir -p "$1"
  cp -R "$root/kit" "$1/kit"
  git -C "$1" init -q
  git -C "$1" add -A
  git -C "$1" -c user.name=t -c user.email=t@example.invalid -c core.hooksPath=/dev/null \
    commit -q -m kit
}

export HOME=$scratch/home
kit_repo "$HOME/git/ystack"
kit=$HOME/git/ystack/kit
claude=$HOME/.claude/CLAUDE.md
codex=$HOME/.codex/AGENTS.md
header=$'---\ndescription: Summon yshifu, the dev-team manager, for the current repo\n---'

# Runs an installer; $1 is the exit code it must return, $2 the installer.
run_at() {
  local want=$1 installer=$2 got
  shift 2
  "$installer" "$@" > "$scratch/out" 2>&1
  got=$?
  [ "$got" -eq "$want" ]
}
run() {
  local want=$1
  shift
  run_at "$want" "$kit/install.sh" "$@"
}
holds() {
  grep -q -F -- "$2" "$1"
}

name='fresh install writes both blocks'
if run 0 && holds "$claude" "@~/git/ystack/kit/rules/working-preferences.md" &&
  holds "$claude" "@~/git/ystack/kit/rules/claude.md" &&
  holds "$codex" "## Working preferences" && holds "$codex" "## Codex model routing"; then pass "$name"; else fail "$name"; fi

name='check reports a current install'
if run 0 --check && holds "$scratch/out" "is current"; then pass "$name"; else fail "$name"; fi

cp "$claude" "$scratch/claude.before"
cp "$codex" "$scratch/codex.before"
name='a second run changes nothing'
if run 0 && [ ! -s "$scratch/out" ] && cmp -s "$claude" "$scratch/claude.before" &&
  cmp -s "$codex" "$scratch/codex.before"; then pass "$name"; else fail "$name"; fi

{
  printf '%s\n' '# Owner notes' '@~/git/other/rules.md'
  cat "$scratch/claude.before"
  printf '%s' 'Text after the block, with no final newline.'
} > "$claude"
cp "$claude" "$scratch/claude.with-notes"
printf '\n- A new routing line.\n' >> "$kit/rules/codex.md"
name='check reports a changed rule as stale'
if run 1 --check && holds "$scratch/out" "stale: ~/.codex/AGENTS.md" &&
  ! holds "$scratch/out" "CLAUDE.md"; then pass "$name"; else fail "$name"; fi
name='a refresh updates the block and keeps other bytes, even with no final newline'
if run 0 && cmp -s "$claude" "$scratch/claude.with-notes" &&
  holds "$codex" "A new routing line." && run 0 --check; then pass "$name"; else fail "$name"; fi

printf 'keep\r\n' > "$codex"
cat "$scratch/codex.before" | sed 's/$/\r/' >> "$codex"
printf 'after\r\n' >> "$codex"
crlf_keep=$(printf 'keep\r')
crlf_after=$(printf 'after\r')
name='a CRLF file keeps its lines outside the block'
if run 0 && [ "$(head -n 1 "$codex")" = "$crlf_keep" ] &&
  [ "$(tail -n 1 "$codex")" = "$crlf_after" ] && holds "$codex" "A new routing line."; then pass "$name"; else fail "$name"; fi

rm "$codex"
printf '%s' '<!-- Generated by another tool. -->' > "$codex"
name='a file without markers keeps its text and gets the block'
if run 0 && [ "$(head -n 1 "$codex")" = "<!-- Generated by another tool. -->" ] &&
  [ "$(sed -n 2p "$codex")" = "" ] && holds "$codex" "<!-- ystack kit: begin"; then pass "$name"; else fail "$name"; fi

printf '%s\n' 'keep' '<!-- ystack kit: begin (old) -->' 'no end' > "$claude"
cp "$claude" "$scratch/broken"
name='broken markers stop the install and change nothing'
if run 2 && holds "$scratch/out" "broken, extra or out-of-order" && cmp -s "$claude" "$scratch/broken"; then pass "$name"; else fail "$name"; fi
printf '%s\n' '<!-- ystack kit: end -->' '<!-- ystack kit: begin (old) -->' > "$claude"
name='markers out of order stop the install'
if run 2 && holds "$scratch/out" "out-of-order"; then pass "$name"; else fail "$name"; fi
printf '%s\n' '<!-- ystack kit: begin (old) -->' 'x' '<!-- ystack kit: end --> owner note' > "$claude"
name='a marker with trailing text is not taken as a marker'
if run 2 && holds "$claude" "owner note"; then pass "$name"; else fail "$name"; fi

sed 's/@~/@~\/old/' "$scratch/claude.before" > "$claude"
cp "$claude" "$scratch/claude.stale"
printf '%s\n' '<!-- ystack kit: begin (old) -->' > "$codex"
name='a late failure writes nothing at all'
if run 2 && cmp -s "$claude" "$scratch/claude.stale"; then pass "$name"; else fail "$name"; fi
rm "$codex"

rm "$claude"
mkdir -p "$HOME/dotfiles"
printf '%s\n' 'linked notes' > "$HOME/dotfiles/CLAUDE.md"
ln -s "$HOME/dotfiles/CLAUDE.md" "$claude"
name='a linked CLAUDE.md stays a link and its target is updated'
if run 0 && [ -L "$claude" ] && holds "$HOME/dotfiles/CLAUDE.md" "linked notes" &&
  holds "$HOME/dotfiles/CLAUDE.md" "@~/git/ystack/kit/rules/claude.md"; then pass "$name"; else fail "$name"; fi

rm "$claude"
ln -s "$HOME/dotfiles/missing.md" "$claude"
name='a link to a missing file stops the install'
if run 2 && holds "$scratch/out" "link to a missing file" && [ ! -e "$HOME/dotfiles/missing.md" ]; then pass "$name"; else fail "$name"; fi
rm "$claude"
ln -s "$codex" "$claude"
printf '%s\n' 'shared' > "$codex"
name='one file shared by both agents stops the install'
if run 2 && holds "$scratch/out" "are the same file"; then pass "$name"; else fail "$name"; fi
rm "$claude" "$codex"
run 0

mkdir -p "$kit/skills/ystack-demo" "$HOME/.claude/skills/someone-else" "$HOME/.agents/skills"
printf '%s\n' '---' 'name: ystack-demo' '---' > "$kit/skills/ystack-demo/SKILL.md"
ln -s "$kit/skills/../rules/missing.md" "$HOME/.agents/skills/foreign"
name='kit skills are linked for both agents'
if run 0 && [ "$(readlink "$HOME/.claude/skills/ystack-demo")" = "$kit/skills/ystack-demo" ] &&
  [ "$(readlink "$HOME/.agents/skills/ystack-demo")" = "$kit/skills/ystack-demo" ] &&
  [ -d "$HOME/.claude/skills/someone-else" ] && run 0 --check; then pass "$name"; else fail "$name"; fi
rm "$kit/skills/ystack-demo/SKILL.md"
name='a skill without SKILL.md loses its links'
if run 1 --check && run 0 && [ ! -L "$HOME/.claude/skills/ystack-demo" ] &&
  [ ! -L "$HOME/.agents/skills/ystack-demo" ]; then pass "$name"; else fail "$name"; fi
name='a foreign link into the kit stays'
if [ -L "$HOME/.agents/skills/foreign" ]; then pass "$name"; else fail "$name"; fi
printf '%s\n' '---' 'name: ystack-demo' '---' > "$kit/skills/ystack-demo/SKILL.md"
mkdir -p "$HOME/.claude/skills/ystack-demo"
name='a folder with the same name is left alone and stops the install'
if run 2 && holds "$scratch/out" "is not this kit" && [ ! -L "$HOME/.claude/skills/ystack-demo" ] &&
  [ ! -L "$HOME/.agents/skills/ystack-demo" ]; then pass "$name"; else fail "$name"; fi
rm -r "$kit/skills/ystack-demo" "$HOME/.claude/skills/ystack-demo"

commands=$HOME/.claude/commands
mkdir -p "$commands"
printf '%s\n%s\n' "$header" 'You are yshifu.' > "$commands/yshifu.md"
cp "$commands/yshifu.md" "$commands/yshifu.md.bak"
printf '%s\n' 'my own command' > "$commands/other.md"
name='the parked yshifu command is removed and others stay'
if run 0 && [ ! -e "$commands/yshifu.md" ] && [ ! -e "$commands/yshifu.md.bak" ] &&
  [ -f "$commands/other.md" ]; then pass "$name"; else fail "$name"; fi
printf '%s\n' 'My notes. Summon yshifu, the dev-team manager, for the current repo.' > "$commands/yshifu.md"
name='a yshifu file without the old header stays'
if run 0 && [ -f "$commands/yshifu.md" ]; then pass "$name"; else fail "$name"; fi

kit_repo "$scratch/elsewhere"
name='a kit outside HOME is imported by its full path'
if run_at 0 "$scratch/elsewhere/kit/install.sh" &&
  holds "$claude" "@$scratch/elsewhere/kit/rules/claude.md"; then pass "$name"; else fail "$name"; fi

kit_repo "$scratch/with space"
name='a kit path with white space is refused'
if run_at 2 "$scratch/with space/kit/install.sh" && holds "$scratch/out" "white space"; then pass "$name"; else fail "$name"; fi

mkdir -p "$scratch/plain"
cp -R "$root/kit" "$scratch/plain/kit"
name='a kit outside any Git checkout is refused'
if run_at 2 "$scratch/plain/kit/install.sh" && holds "$scratch/out" "inside a Git checkout"; then pass "$name"; else fail "$name"; fi

git -C "$HOME/git/ystack" worktree add -q "$scratch/linked" 2> /dev/null
name='a linked worktree is refused'
if run_at 2 "$scratch/linked/kit/install.sh" --check && holds "$scratch/out" "not from a linked worktree"; then pass "$name"; else fail "$name"; fi

if [ "$failures" -gt 0 ]; then
  echo "$failures case(s) failed"
  exit 1
fi
echo "all cases passed"
